// Package xmlgen writes large, deterministic XML documents for benchmarks.
//
// The documents are built from car records like the ones in
// testdata/example.xml, mixed with the things that make real XML slow to
// scan: deep nesting, many attributes, comments, CDATA sections,
// processing instructions and a DOCTYPE with an internal subset.
package xmlgen

import (
	"bufio"
	"fmt"
	"io"
	"math/rand/v2"
)

// Options control the generated document. The zero value of a field
// selects its default.
type Options struct {
	Size  int64  // approximate size in bytes; the document ends after the first record past it
	Depth int    // nesting depth of the deep option chain in some records (default 40)
	Seed  uint64 // random seed; the same seed gives the same document
}

const defaultDepth = 40

var (
	makers  = []string{"Volvo", "Saab", "Scania", "Koenigsegg", "Polestar"}
	colors  = []string{"blue", "red", "yellow", "black", "white", "silver"}
	fuels   = []string{"Gasoline", "Diesel", "Electric", "Hybrid", "Ethanol"}
	models  = []string{"V70", "900", "R-series", "Agera", "P2", "XC90", "9-3"}
	country = []string{"SE", "NO", "DK", "FI", "DE"}
	words   = []string{"the", "car", "was", "kept", "in", "a", "garage", "and", "serviced", "every", "year",
		"by", "its", "first", "owner", "who", "drove", "it", "mostly", "on", "long", "trips", "along", "coast",
		"with", "new", "tyres", "fitted", "last", "winter", "minor", "rust", "on", "rear", "doors", "&amp;", "roof"}
)

// Write writes a document of about opts.Size bytes to w.
func Write(w io.Writer, opts Options) error {
	if opts.Depth <= 0 {
		opts.Depth = defaultDepth
	}
	cw := &countingWriter{w: w}
	bw := bufio.NewWriterSize(cw, 256*1024)
	rng := rand.New(rand.NewPCG(opts.Seed, opts.Seed^0x9e3779b97f4a7c15))

	bw.WriteString(header)
	for i := 1; cw.n+int64(bw.Buffered()) < opts.Size; i++ {
		writeCar(bw, rng, i, opts.Depth)
		if cw.err != nil {
			return cw.err
		}
	}
	bw.WriteString("</cars>\n")
	if err := bw.Flush(); err != nil {
		return err
	}
	return cw.err
}

const header = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE cars [
	<!ELEMENT cars (car|info)*>
	<!ATTLIST car vin CDATA #REQUIRED man CDATA #IMPLIED>
	<!ENTITY note "generated > data">
]>
<!-- Generated by saxer-gen. Car records modelled on testdata/example.xml. -->
<cars xmlns:xs="urn:example:xs">
`

func writeCar(w *bufio.Writer, rng *rand.Rand, i, depth int) {
	pick := func(s []string) string { return s[rng.IntN(len(s))] }
	fmt.Fprintf(w, "\t<car vin=\"wp%07d\" man=\"%s\" model=\"%s\" year=\"%d\" country=\"%s\" doors=\"%d\" weight=\"%d\" price=\"%d\" owner-count=\"%d\" registered=\"true\">\n",
		i, pick(makers), pick(models), 1980+rng.IntN(45), pick(country), 2+2*rng.IntN(2), 900+rng.IntN(1500), 10000+rng.IntN(90000), rng.IntN(6))
	fmt.Fprintf(w, "\t\t<color>%s</color>\n", pick(colors))
	w.WriteString("\t\t<description>")
	for j, n := 0, 20+rng.IntN(60); j < n; j++ {
		if j > 0 {
			w.WriteByte(' ')
		}
		w.WriteString(pick(words))
	}
	w.WriteString(".</description>\n")
	fmt.Fprintf(w, "\t\t<xs:doors>%d</xs:doors>\n", 2+2*rng.IntN(2))
	fmt.Fprintf(w, "\t\t<engine nr=\"%07d\" cylinders=\"%d\" volume=\"%d.%d\" turbo=\"%t\">\n", i, 3+rng.IntN(6), 1+rng.IntN(4), rng.IntN(10), rng.IntN(2) == 0)
	fmt.Fprintf(w, "\t\t\t<Fuel>%s</Fuel>\n", pick(fuels))
	w.WriteString("\t\t</engine>\n")
	if i%3 == 0 {
		fmt.Fprintf(w, "\t\t<!-- service record %d: <checked> & approved -->\n", i)
	}
	if i%4 == 0 {
		fmt.Fprintf(w, "\t\t<notes><![CDATA[Owner wrote: <b>fast</b> & reliable, %d km]]></notes>\n", rng.IntN(400000))
	}
	if i%5 == 0 {
		fmt.Fprintf(w, "\t\t<?inspection passed=\"%t\"?>\n", rng.IntN(4) != 0)
	}
	if i%10 == 0 {
		w.WriteString("\t\t<history>\n")
		for j := 0; j < 1+rng.IntN(4); j++ {
			fmt.Fprintf(w, "\t\t\t<owner from=\"%d\" name=\"Owner &amp; Co %d\"/>\n", 1990+rng.IntN(35), j)
		}
		w.WriteString("\t\t</history>\n")
	}
	if i%50 == 0 {
		// A deep chain of nested options.
		for d := 0; d < depth; d++ {
			fmt.Fprintf(w, "<option level=\"%d\">", d)
		}
		w.WriteString("<extra>deep</extra>")
		for d := 0; d < depth; d++ {
			w.WriteString("</option>")
		}
		w.WriteString("\n")
	}
	w.WriteString("\t</car>\n")
	if i%200 == 0 {
		fmt.Fprintf(w, "\t<info>&lt;batch nr=\"%d\"&gt;</info>\n", i/200)
	}
}

type countingWriter struct {
	w   io.Writer
	n   int64
	err error
}

func (c *countingWriter) Write(p []byte) (int, error) {
	if c.err != nil {
		return 0, c.err
	}
	n, err := c.w.Write(p)
	c.n += int64(n)
	c.err = err
	return n, err
}
